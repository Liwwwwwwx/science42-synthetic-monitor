export const RESEARCH_QUESTIONS = TOPICS.flatMap(([category, topic, domain], topicIndex) =>
  LENSES.map((lens, lensIndex) => ({
    id: `${String(topicIndex + 1).padStart(2, '0')}-${lensIndex + 1}`,
    category,
    topic,
    domain,
    variant: lensIndex + 1,
    prompt: `研究主题为“${topic}”，所属方向为${domain}。${lens}`,
  })),
);

export function getResearchQuestion(id) {
  return RESEARCH_QUESTIONS.find((item) => item.id === id) || null;
}
